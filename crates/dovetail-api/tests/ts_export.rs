//! Writes the protocol's TypeScript declarations to `gui/src/core/generated/` (ADR 0023).
//!
//! Run with `cargo test -p dovetail-api --features ts --test ts_export`. The files are committed;
//! `scripts/check.sh` runs this and fails when they changed, so a Rust change that the GUI has
//! not taken in cannot merge.

use std::path::Path;

use dovetail_api::{Command, ServerMsg};
use ts_rs::{Config, TS};

#[test]
fn export_the_protocol_for_the_gui() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../gui/src/core/generated");
    // Start clean, so a type that left the protocol leaves the folder too.
    if dir.exists() {
        for entry in std::fs::read_dir(&dir).expect("read the folder") {
            let path = entry.expect("an entry").path();
            if path.extension().is_some_and(|e| e == "ts") {
                std::fs::remove_file(&path).expect("remove an old file");
            }
        }
    }
    // Every id and time fits a JavaScript number exactly; JSON.parse gives numbers, not bigints.
    let cfg = Config::new().with_large_int("number").with_out_dir(&dir);
    ServerMsg::export_all(&cfg).expect("export ServerMsg");
    Command::export_all(&cfg).expect("export Command");
    let mut names: Vec<String> = std::fs::read_dir(&dir)
        .expect("read the folder")
        .filter_map(|e| {
            let name = e.ok()?.file_name().into_string().ok()?;
            name.strip_suffix(".ts").map(str::to_owned)
        })
        .filter(|n| n != "index")
        .collect();
    names.sort();
    let mut index =
        String::from("// Generated by crates/dovetail-api/tests/ts_export.rs. Do not edit.\n");
    for name in names {
        index.push_str(&format!("export type {{ {name} }} from './{name}';\n"));
    }
    std::fs::write(dir.join("index.ts"), index).expect("write index.ts");
}
